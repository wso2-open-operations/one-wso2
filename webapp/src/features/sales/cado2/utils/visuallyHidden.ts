/**
 * Hides text on screen but keeps it for screen readers, e.g. a table's
 * "Actions" heading. Sizes are in px on purpose: in MUI's sx, `width: 1`
 * means 100%, which made the "hidden" box as big as the table and gave it
 * scroll bars in some themes (2026-10-24).
 */
export const visuallyHidden = {
  position: "absolute",
  width: "1px",
  height: "1px",
  padding: 0,
  margin: "-1px",
  overflow: "hidden",
  clip: "rect(0 0 0 0)",
  whiteSpace: "nowrap",
  border: 0,
} as const;
