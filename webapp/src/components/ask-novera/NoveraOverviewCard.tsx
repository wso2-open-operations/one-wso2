/**
 * Regex matching markdown links [Label](url) and bare URLs (https?://...).
 */
const LINK_REGEX = /\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)|(https?:\/\/[^\s<)]+)/g;

/**
 * Parses raw text containing markdown links or bare URLs into styled, clickable Link components.
 *
 * @param text - Plain text response from Novera
 * @returns Array of strings and styled Link components
 */
function renderFormattedContent(text: string): React.ReactNode {
  const elements: React.ReactNode[] = [];
  let lastIndex = 0;
  let match: RegExpExecArray | null;

  // Reset regex state
  LINK_REGEX.lastIndex = 0;

  while ((match = LINK_REGEX.exec(text)) !== null) {
    if (match.index > lastIndex) {
      elements.push(text.substring(lastIndex, match.index));
    }

    if (match[1] && match[2]) {
      // Markdown link: [label](url)
      const label = match[1];
      const url = match[2];
      elements.push(
        <Link
          key={`md-${match.index}`}
          href={url}
          target="_blank"
          rel="noopener noreferrer"
          onClick={(e: React.MouseEvent) => e.stopPropagation()}
          sx={{
            color: "primary.main",
            textDecoration: "underline",
            textUnderlineOffset: "3px",
            fontWeight: 600,
            wordBreak: "break-all",
            cursor: "pointer",
            "&:hover": {
              color: "primary.dark",
              textDecoration: "underline",
            },
          }}
        >
          {label}
        </Link>,
      );
    } else if (match[3]) {
      // Bare URL: https://...
      let rawUrl = match[3];
      let trailingPunct = "";
      const punctMatch = rawUrl.match(/[,.;:!?)]+$/);
      if (punctMatch) {
        trailingPunct = punctMatch[0];
        rawUrl = rawUrl.slice(0, -trailingPunct.length);
      }

      elements.push(
        <Link
          key={`raw-${match.index}`}
          href={rawUrl}
          target="_blank"
          rel="noopener noreferrer"
          onClick={(e: React.MouseEvent) => e.stopPropagation()}
          sx={{
            color: "primary.main",
            textDecoration: "underline",
            textUnderlineOffset: "3px",
            fontWeight: 600,
            wordBreak: "break-all",
            cursor: "pointer",
            "&:hover": {
              color: "primary.dark",
              textDecoration: "underline",
            },
          }}
        >
          {rawUrl}
        </Link>,
      );

      if (trailingPunct) {
        elements.push(trailingPunct);
      }
    }

    lastIndex = match.index + match[0].length;
  }

  if (lastIndex < text.length) {
    elements.push(text.substring(lastIndex));
  }

  return elements;
}

interface NoveraOverviewCardProps {
  /** Text content generated by Novera */
  text: string;
  /** Whether Novera is actively streaming or waiting for a response */
  isLoading?: boolean;
  /** Controlled expansion state */
  expanded?: boolean;
  /** Callback invoked when the user toggles Show more / Show less */
  onToggleExpand?: (expanded: boolean) => void;
  /** Optional embedded children (such as the follow-up input bar) */
  children?: React.ReactNode;
  /** Whether an action/navigation button card is rendered below this overview */
  hasActionCard?: boolean;
  /** Whether a user message bubble is rendered above this overview on the canvas */
  hasUserMessageAbove?: boolean;
}

/**
 * Truncates long text cleanly to a generous line height (default 7-8 lines or ~480 characters),
 * preserving clean word and line boundaries with comfortable readability.
 *
 * @param fullText - The full message string
 * @param maxLines - Maximum non-empty lines to preserve (default 7)
 * @param maxChars - Maximum characters to preserve (default 480)
 * @returns Shortened string ending cleanly
 */
function getTruncatedText(fullText: string, maxLines = 7, maxChars = 480): string {
  const lines = fullText.split("\n");
  if (lines.length > maxLines) {
    let count = 0;
    const kept: string[] = [];
    for (const line of lines) {
      kept.push(line);
      if (line.trim().length > 0) {
        count++;
      }
      if (count >= maxLines) {
        break;
      }
    }
    const joined = kept.join("\n").trimEnd();
    if (joined.length < fullText.trimEnd().length) {
      return joined.replace(/[.,;!?]+$/, "") + "...";
    }
  }

  if (fullText.length > maxChars) {
    const slice = fullText.slice(0, maxChars);
    const lastSpace = slice.lastIndexOf(" ");
    const cleanSlice = lastSpace > (maxChars - 90) ? slice.slice(0, lastSpace) : slice;
    return cleanSlice.trimEnd().replace(/[.,;!?]+$/, "") + "...";
  }

  return fullText;
}

/** Pulse animation for the Sparkles badge while Novera is thinking. */
const pulseAnimation = keyframes`
  0%, 100% {
    transform: scale(1);
    opacity: 1;
  }
  50% {
    transform: scale(1.12);
    opacity: 0.8;
  }
`;

/** Smooth fade-in and slight upward slide when overview content materializes. */
const fadeInContent = keyframes`
  from {
    opacity: 0;
    transform: translateY(4px);
  }
  to {
    opacity: 1;
    transform: translateY(0);
  }
`;

/**
 * AI Overview card rendered at the top of search results,
 * dynamically styled to adapt to the active theme palette.
 */
export default function NoveraOverviewCard({
  text,
  isLoading,
  expanded: controlledExpanded,
  onToggleExpand,
  children,
  hasActionCard = false,
  hasUserMessageAbove = false,
}: NoveraOverviewCardProps) {
  const [internalExpanded, setInternalExpanded] = useState<boolean>(false);
  const isExpanded = controlledExpanded !== undefined ? controlledExpanded : internalExpanded;
  const cardRef = useRef<HTMLDivElement>(null);
  const contentRef = useRef<HTMLDivElement>(null);
  const [isLong, setIsLong] = useState<boolean>(false);

  // Consider the user message, overview, and navigation button together for screen visibility.
  // The active turn unit should comfortably fit within 3/4 of the viewport (window.innerHeight * 0.75)
  // so the navigation button is never pushed out of screen view.
  const userMessageSpace = hasUserMessageAbove ? 60 : 0;
  const actionCardSpace = hasActionCard ? 96 : 0;
  const maxTurnBudget =
    typeof window !== "undefined" && window.innerHeight > 0 ? window.innerHeight * 0.75 : 560;
  const maxOverviewHeight = Math.max(220, maxTurnBudget - userMessageSpace - actionCardSpace);

  // Pre-check threshold adjusted when sibling elements (action card / user message) are present
  const charThreshold = hasActionCard ? 450 : 560;
  const lineThreshold = hasActionCard ? 7 : 9;
  const mightBeLong =
    text.length > charThreshold || (text.match(/\n/g) || []).length >= lineThreshold;

  const truncatedLines = hasActionCard ? 6 : 8;
  const truncatedChars = hasActionCard ? 420 : 520;

  useEffect(() => {
    if (!mightBeLong) {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setIsLong(false);
      return;
    }
    const cardEl = cardRef.current;
    const contentEl = contentRef.current;
    const targetEl = cardEl || contentEl;
    if (!targetEl) {
      // JSDOM / SSR: fall back to character count heuristic
      setIsLong(mightBeLong);
      return;
    }
    const renderedHeight = targetEl.getBoundingClientRect().height;
    if (renderedHeight === 0) {
      // JSDOM returns 0 for all layout measurements; use char count fallback
      setIsLong(
        text.length > charThreshold || (text.match(/\n/g) || []).length >= lineThreshold,
      );
      return;
    }
    setIsLong(renderedHeight > maxOverviewHeight);
  }, [text, mightBeLong, maxOverviewHeight, charThreshold, lineThreshold]);

  const handleToggle = () => {
    const next = !isExpanded;
    if (onToggleExpand) {
      onToggleExpand(next);
    } else {
      setInternalExpanded(next);
    }
  };

  const showToggle = isLong;

  return (
    <Box
      ref={cardRef}
      sx={{
        p: 2.25,
        borderRadius: 1.5,
        position: "relative",
        overflow: "hidden",
        bgcolor: (t) =>
          t.vars
            ? `rgba(${t.vars.palette.primary.mainChannel} / ${t.palette.mode === "dark" ? 0.1 : 0.04})`
            : alpha(t.palette.primary.main, t.palette.mode === "dark" ? 0.1 : 0.04),
        border: 1,
        borderColor: (t) =>
          t.vars
            ? `rgba(${t.vars.palette.primary.mainChannel} / ${t.palette.mode === "dark" ? 0.28 : 0.18})`
            : alpha(t.palette.primary.main, t.palette.mode === "dark" ? 0.28 : 0.18),
        display: "flex",
        flexDirection: "column",
        gap: 1.25,
        "&::before": {
          content: '""',
          position: "absolute",
          top: 0,
          left: 0,
          right: 0,
          height: "3px",
          background: (t: Theme) =>
            `linear-gradient(90deg, ` +
            `var(--oxygen-palette-primary-main, ${t.palette.primary.main}) 0%, ` +
            `var(--oxygen-palette-secondary-main, ${
              t.palette.secondary?.main || t.palette.primary.light
            }) 50%, ` +
            `var(--oxygen-palette-info-main, ${t.palette.info?.main || t.palette.primary.light}) 100%)`,
        },
      }}
    >
      {/* Header bar: Theme-adaptive Sparkles badge and gradient title */}
      <Box sx={{ display: "flex", alignItems: "center", gap: 1 }}>
        <Box
          sx={{
            display: "inline-flex",
            p: 0.6,
            borderRadius: 0.75,
            background: (t) =>
              `linear-gradient(135deg, ` +
              `rgba(${t.vars?.palette.primary.mainChannel ?? "255, 115, 0"} / ${
                t.palette.mode === "dark" ? 0.25 : 0.14
              }) 0%, ` +
              `rgba(${t.vars?.palette.secondary?.mainChannel ?? "255, 168, 82"} / ${
                t.palette.mode === "dark" ? 0.2 : 0.1
              }) 100%)`,
            color: "primary.main",
            animation: isLoading ? `${pulseAnimation} 1.8s ease-in-out infinite` : "none",
            "@media (prefers-reduced-motion: reduce)": {
              animation: "none",
            },
          }}
        >
          <SparklesIcon size={14} />
        </Box>
        <Typography
          variant="caption"
          sx={{
            fontWeight: 700,
            textTransform: "uppercase",
            letterSpacing: 0.6,
            color: "primary.main",
            fontSize: 11.5,
          }}
        >
          Novera Overview
        </Typography>
      </Box>

      {/* Shimmering Skeleton Loader while generating (Google Gemini / Search style) */}
      {isLoading && !text ? (
        <Box
          role="status"
          aria-live="polite"
          aria-label="Generating AI Overview..."
          sx={{
            display: "flex",
            flexDirection: "column",
            gap: 1.25,
            pt: 0.5,
          }}
        >
          <Box sx={{ display: "flex", alignItems: "center", gap: 1, mb: 0.25 }}>
            <CircularProgress size={12} thickness={5} sx={{ color: "primary.main" }} />
            <Typography
              variant="caption"
              color="text.secondary"
              sx={{ fontSize: 11.5, fontWeight: 500 }}
            >
              Novera is thinking...
            </Typography>
          </Box>
          <Skeleton
            animation="wave"
            variant="rounded"
            height={13}
            width="100%"
            sx={{
              borderRadius: 0.75,
              bgcolor: (t) =>
                t.vars
                  ? `rgba(${t.vars.palette.primary.mainChannel} / ${t.palette.mode === "dark" ? 0.16 : 0.08})`
                  : alpha(t.palette.primary.main, t.palette.mode === "dark" ? 0.16 : 0.08),
            }}
          />
          <Skeleton
            animation="wave"
            variant="rounded"
            height={13}
            width="90%"
            sx={{
              borderRadius: 0.75,
              bgcolor: (t) =>
                t.vars
                  ? `rgba(${t.vars.palette.primary.mainChannel} / ${t.palette.mode === "dark" ? 0.14 : 0.07})`
                  : alpha(t.palette.primary.main, t.palette.mode === "dark" ? 0.14 : 0.07),
            }}
          />
          <Skeleton
            animation="wave"
            variant="rounded"
            height={13}
            width="65%"
            sx={{
              borderRadius: 0.75,
              bgcolor: (t) =>
                t.vars
                  ? `rgba(${t.vars.palette.primary.mainChannel} / ${t.palette.mode === "dark" ? 0.12 : 0.06})`
                  : alpha(t.palette.primary.main, t.palette.mode === "dark" ? 0.12 : 0.06),
            }}
          />
        </Box>
      ) : (
        /* Overview content with smooth fade-in arrival */
        Boolean(text) && (
          <Box
            ref={contentRef}
            sx={{
              fontSize: 14,
              lineHeight: 1.6,
              color: "text.primary",
              whiteSpace: "pre-wrap",
              wordBreak: "break-word",
              animation: `${fadeInContent} 0.3s cubic-bezier(0.16, 1, 0.3, 1) both`,
              "@media (prefers-reduced-motion: reduce)": {
                animation: "none",
              },
            }}
          >
            {renderFormattedContent(
              isExpanded || !isLong ? text : getTruncatedText(text, truncatedLines, truncatedChars),
            )}
            {!isExpanded && isLong && " "}
            {showToggle && (
              <Button
                size="small"
                variant="text"
                onClick={handleToggle}
                endIcon={isExpanded ? <ChevronUpIcon size={14} /> : <ChevronDownIcon size={14} />}
                sx={{
                  display: "inline-flex",
                  verticalAlign: "baseline",
                  p: 0,
                  ml: 0.75,
                  minWidth: 0,
                  fontSize: 12.5,
                  fontWeight: 600,
                  textTransform: "none",
                  color: "primary.main",
                  lineHeight: "inherit",
                  "&:hover": { bgcolor: "transparent", textDecoration: "underline" },
                }}
              >
                {isExpanded ? "Show less" : "Show more"}
              </Button>
            )}
          </Box>
        )
      )}

      {/* Loading indicator for follow-up streaming when previous text exists */}
      {isLoading && Boolean(text) && (
        <Box sx={{ display: "flex", alignItems: "center", gap: 1, pt: 0.5 }}>
          <CircularProgress size={12} thickness={5} sx={{ color: "primary.main" }} />
          <Typography variant="caption" color="text.secondary" sx={{ fontSize: 11.5 }}>
            Novera is thinking...
          </Typography>
        </Box>
      )}

      {/* Embedded follow-up input or extra content inside overview reply */}
      {children}
    </Box>
  );
}
